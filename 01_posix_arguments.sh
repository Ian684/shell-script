#!/bin/sh
set -eu
topic="posix_arguments"
values="12 7 19 3 25"
sum=0
count=0
maximum=
minimum=
for value in $values
do
    sum=$((sum + value))
    count=$((count + 1))
    if [ -z "$maximum" ] || [ "$value" -gt "$maximum" ]; then maximum=$value; fi
    if [ -z "$minimum" ] || [ "$value" -lt "$minimum" ]; then minimum=$value; fi
done
printf 'Exercise %02d: %s
' "1" "$topic"
printf 'Sum: %d Maximum: %d Minimum: %d Count: %d
' "$sum" "$maximum" "$minimum" "$count"
printf 'Arguments: %s
' "$*"
printf 'Values: %s
' "$values"
printf 'Sorted: '
printf '%s
' $values | sort -n | tr '
' ' '
printf '
'

